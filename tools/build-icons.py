#!/usr/bin/env python3
"""Build the home-screen app icons for every Daily Maverick town.

iPhones and Chrome want PNG icons to install a site as an app, and a Worker
can't draw PNGs, so we draw them here once and bake them into src/icons.js.
Run after adding a new town to src/regions.js:  python3 tools/build-icons.py
Needs Pillow (pip install pillow) and the DejaVu Sans Bold font.
"""
import base64, io, pathlib, re
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
codes = sorted(set(re.findall(r'code:\s*"(\d{4})"', (ROOT / "src/regions.js").read_text())))
SIZES = (180, 192, 512)
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
NAVY, GOLD, WHITE = (11, 21, 38), (245, 183, 0), (255, 255, 255)

def draw(code, size=1024):
    # Full-bleed square (phones round the corners themselves); everything sits inside the maskable safe zone.
    k = size / 512
    im = Image.new("RGB", (size, size), NAVY)
    d = ImageDraw.Draw(im)
    pts = [(150, 392), (205, 282), (248, 350), (291, 258), (362, 392)]
    d.line([(x * k, y * k) for x, y in pts], fill=GOLD, width=round(18 * k), joint="curve")
    for x, y in (pts[0], pts[-1]):
        r = 9 * k; d.ellipse([x * k - r, y * k - r, x * k + r, y * k + r], fill=GOLD)
    d.ellipse([(291 - 17) * k, (258 - 17) * k, (291 + 17) * k, (258 + 17) * k], fill=GOLD)
    f = ImageFont.truetype(FONT, round(106 * k))
    d.text((256 * k, 170 * k), code, font=f, fill=WHITE, anchor="mm")
    return im

out = {}
for c in codes:
    big = draw(c); out[c] = {}
    for s in SIZES:
        buf = io.BytesIO()
        big.resize((s, s), Image.LANCZOS).quantize(64).save(buf, "PNG", optimize=True)
        out[c][s] = base64.b64encode(buf.getvalue()).decode()

lines = ["// Generated by tools/build-icons.py. Do not edit by hand: re-run the script after adding a town.",
         "// Home-screen app icons (PNG, base64) for each Daily Maverick, by postcode and size.",
         "export const ICONS = {"]
for c, sizes in out.items():
    lines.append(f'  "{c}": {{ ' + ", ".join(f'{s}: "{b}"' for s, b in sizes.items()) + " },")
lines.append("};\n")
(ROOT / "src/icons.js").write_text("\n".join(lines))
print(f"Built icons for {', '.join(codes)}")
